function treasure(
  id: string,
  nameZh: string,
  nameEn: string,
  rarity: Rarity,
  value: number,
  shape: number[][],
  layerId: string,
): TreasureConfig {
  return { id, nameZh, nameEn, rarity, value, shape, layerId, color: RARITY_COLORS[rarity] };
}

function skill(
  id: string,
  nameZh: string,
  nameEn: string,
  branch: SkillBranchId,
  requires: string[],
  tier: number,
): SkillNodeConfig {
  return { id, nameZh, nameEn, branch, requires, tier };
}

